import assert from 'node:assert/strict';
import {toStudioPeople} from '../src/utils/studioAdapter';
import type {FamilyMember,FamilyUnion,FamilyChild} from '../src/types/family';
const mk=(id:string,full_name:string,gender:'male'|'female'):FamilyMember=>({id,tree_id:'tree-1',full_name,gender});
const members=[mk('grandpa','Abdul Mannan','male'),mk('anwar','Anwar Kamal','male'),mk('ruhi1','Ruhi Kamal','female'),mk('ruhi2','Ruhi Fakhir','female'),mk('ghani','Abdul Ghani','male'),mk('sidra','Sidra Kamal','female')];
const unions:FamilyUnion[]=[{id:'parents',tree_id:'tree-1',partner1_id:'grandpa',partner2_id:null,relationship_type:'single_parent',marriage_status:'unknown'},{id:'first',tree_id:'tree-1',partner1_id:'anwar',partner2_id:'ruhi1',relationship_type:'spouse',marriage_status:'married'},{id:'second',tree_id:'tree-1',partner1_id:'anwar',partner2_id:'ruhi2',relationship_type:'spouse',marriage_status:'married'}];
const links:FamilyChild[]=[{id:'l0',tree_id:'tree-1',family_union_id:'parents',child_id:'anwar',relationship_type:'biological'},{id:'l1',tree_id:'tree-1',family_union_id:'first',child_id:'ghani',relationship_type:'biological'},{id:'l2',tree_id:'tree-1',family_union_id:'second',child_id:'sidra',relationship_type:'biological'}];
const people=toStudioPeople(members,unions,links);
const get=(id:string)=>people.find(p=>p.id===id)!;
assert.equal(people.length,6);
assert.equal(get('anwar').spouses.length,2);
assert.deepEqual(get('ghani').parentIds.sort(),['anwar','ruhi1']);
assert.deepEqual(get('sidra').parentIds.sort(),['anwar','ruhi2']);
assert.equal(get('ghani').marriageBranchId,'first');
assert.equal(get('sidra').marriageBranchId,'second');
assert.equal(get('ghani').motherId,'ruhi1');
assert.equal(get('sidra').motherId,'ruhi2');
assert.equal(get('anwar').fatherId,'grandpa');
assert.equal(get('ghani').generation,3);
console.log('Studio adapter: 10 assertions passed');
